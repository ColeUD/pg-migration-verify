-- Profiles, projects and todos for a demo app, in the style of a Supabase migration.
-- Synthetic schema written for the pg-migration-verify test suite.

create extension if not exists "pgcrypto" with schema extensions;

create type public.todo_status as enum ('open', 'in_progress', 'done');

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  username text unique,
  full_name text,
  avatar_url text,
  updated_at timestamptz default now(),
  constraint username_length check (char_length(username) >= 3)
);

alter table public.profiles enable row level security;

create policy "Public profiles are viewable by everyone."
  on public.profiles for select
  using (true);

create policy "Users can insert their own profile."
  on public.profiles for insert
  with check ((select auth.uid()) = id);

create table public.projects (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles (id) on delete cascade,
  name varchar(120) not null,
  created_at timestamptz not null default now()
);

create table public.todos (
  id bigint generated by default as identity primary key,
  project_id uuid not null references public.projects (id) on delete cascade,
  title text not null,
  status public.todo_status not null default 'open',
  due_on date,
  inserted_at timestamp with time zone default timezone('utc'::text, now()) not null
);

create index todos_project_id_idx on public.todos (project_id);
create unique index projects_owner_name_key on public.projects (owner_id, lower(name));

alter table public.projects enable row level security;
alter table public.todos enable row level security;

create policy "Owners manage their projects" on public.projects
  for all to authenticated
  using ((select auth.uid()) = owner_id)
  with check ((select auth.uid()) = owner_id);

-- Keep profiles in sync with auth.users.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, avatar_url)
  values (new.id, new.raw_user_meta_data->>'full_name', new.raw_user_meta_data->>'avatar_url');
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- Storage bucket for avatars.
insert into storage.buckets (id, name) values ('avatars', 'avatars');

create policy "Avatar images are publicly accessible." on storage.objects
  for select using (bucket_id = 'avatars');

alter publication supabase_realtime add table public.todos;

grant usage on schema public to anon, authenticated;
